CREATE TABLE IF NOT EXISTS `quiz_question` (
  `id`         bigint       NOT NULL AUTO_INCREMENT COMMENT '主键',
  `subject`    varchar(16)  NOT NULL COMMENT 'ds/co/os/cn',
  `chapter`    varchar(64)  NOT NULL DEFAULT '' COMMENT '章节',
  `source`     varchar(32)  NOT NULL DEFAULT '章节练习' COMMENT '来源：章节练习 / 2023 真题 等',
  `question`   text         NOT NULL COMMENT '题干',
  `options`    text         NOT NULL COMMENT '选项 JSON 数组',
  `answer`     varchar(4)   NOT NULL COMMENT '正确选项字母',
  `analysis`   text         NULL COMMENT '解析',
  `createTime` datetime     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_subject` (`subject`, `source`)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT ='408 在线习题';

CREATE TABLE IF NOT EXISTS `quiz_record` (
  `id`         bigint      NOT NULL AUTO_INCREMENT COMMENT '主键',
  `userId`     bigint      NOT NULL COMMENT '用户 id',
  `questionId` bigint      NOT NULL COMMENT '题目 id',
  `chosen`     varchar(4)  NOT NULL COMMENT '所选选项',
  `correct`    int         NOT NULL DEFAULT 0 COMMENT '1 对 / 0 错',
  `createTime` datetime    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_user` (`userId`)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT ='习题作答记录';

